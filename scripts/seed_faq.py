def seed_faq():
    Base.metadata.create_all(bind=engine)
    ensure_schema_upgrades()
    db = SessionLocal()
    try:
        added = 0
        for item in FAQ_DATA:
            exists = db.query(FaqEntry).filter_by(question=item["question"]).first()
            if not exists:
                db.add(FaqEntry(
                    question=item["question"],
                    answer=item["answer"],
                    topic=item["topic"],
                    keywords=item["keywords"],
                    status="answered_auto",
                    is_active=True,
                ))
                added += 1
        review_added = 0
        for item in FAQ_REVIEW_DATA:
            exists = db.query(FaqEntry).filter_by(question=item["question"]).first()
            if not exists:
                db.add(FaqEntry(
                    question=item["question"],
                    answer=item["answer"],
                    topic=item["topic"],
                    keywords="",
                    status="needs_review",
                    review_reason=item["review_reason"],
                    is_active=True,
                ))
                review_added += 1
        db.commit()
        total = db.query(FaqEntry).count()
        print(f"FAQ seed done: answered_auto added={added}, needs_review added={review_added}, total={total} "
              f"(из {len(FAQ_DATA)} + {len(FAQ_REVIEW_DATA)} в файле)")
    finally:
        db.close()


if __name__ == "__main__":
    seed_faq()
